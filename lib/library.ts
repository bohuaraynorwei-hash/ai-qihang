export type LibraryType = "prompt" | "agent" | "skill";

export interface LibraryItem {
  id: string;
  type: LibraryType;
  title: string;
  /** 一句话：它帮你解决什么 */
  goal: string;
  /** 什么时候用它 */
  when: string;
  /** 什么时候**别**用它（照抄旧平台的防误用设计，最容易被忽略但最值钱） */
  whenNot?: string;
  /** 推荐模型 / 工具 */
  model?: string;
  /** 用它之后你会拿到什么 */
  output?: string;
  /** 可直接复制的内容（提示词 / Agent 配置 / Skill 说明书） */
  content: string;
  tags: string[];
  level: "入门" | "进阶";
}

